## Test evidence

Element 4 asks for the results of the verification and validation tests. What
exists is FerroEHR's openEHR conformance record (the run of the latest released
Veredictum profile, an independent instrument, against a composed deployment:
`results.json` and `summary.md` under `docs/conformance/ferroehr/`, with the
