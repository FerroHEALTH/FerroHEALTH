emit() {
  local target="$1" body="$2"
  if [[ "$CHECK" -eq 1 ]]; then
    [[ -f "$target" ]] || die "$target does not exist; run $SCRIPT"
    if ! diff -u "$target" "$body" > "$WORK/diff"; then
      cat "$WORK/diff" >&2
      die "$target is stale against $SRC; run $SCRIPT and commit the result"
    fi
  else
    mkdir -p "$(dirname "$target")"
    cp "$body" "$target"
  fi
}

render_readiness > "$WORK/readiness.md"
render_techdoc  > "$WORK/techdoc.md"
emit "$READINESS" "$WORK/readiness.md"
emit "$TECHDOC"   "$WORK/techdoc.md"

count="$(jq '[.requirements[].items[]] | length' "$WORK/ehds.json")"
if [[ "$CHECK" -eq 1 ]]; then
  echo "ehds-pages: both pages match $SRC ($count Annex II requirements)"
else
  echo "ehds-pages: wrote $READINESS and $TECHDOC ($count Annex II requirements)"
fi
