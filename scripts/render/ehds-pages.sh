## What CRA Annex VII adds

CRA Annex VII asks for four things Annex III does not, each with its own file
in each product's repository: the design, development and vulnerability-handling processes
with the software bills of materials (point 2), the cybersecurity
risk assessment (point 3, [FerroEHR's](https://ferroehr.eu/docs/latest/compliance/cra-risk-assessment.html)), the information taken
into account to set the support period, the five-year commitment to publish
security fixes (point 4), and the standards applied or
